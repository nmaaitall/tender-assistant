from __future__ import annotations

from app.retrieval import Hit

SYSTEM_PROMPT = """أنت مساعد يجيب عن أسئلة حول كراسة شروط عطاء حكومي أردني.

أجب من المقاطع المرفقة فقط. لا تستخدم أي معرفة خارجية ولا تستنتج ما لم يُكتب.
إذا لم تذكر المقاطع الجواب، اجعل answer قيمته null ولا تخمّن.
انتبه إلى البنود المتشابهة: كفالة دخول العطاء غير كفالة حسن التنفيذ، وآخر موعد لتقديم
العروض غير مدة تنفيذ المشروع.

اكتب الجواب بالعربية في جملة أو جملتين، واكتب المبالغ والأعداد والتواريخ بالأرقام.
لكل معلومة في الجواب أضف اقتباسا منسوخا حرفيا من مقطع واحد مع رقم صفحته.

أعد JSON فقط بهذا الشكل:
{"answer": "..." أو null, "citations": [{"page": رقم الصفحة, "quote": "نص منسوخ حرفيا"}]}"""


def build_prompt(question: str, hits: list[Hit]) -> str:
    passages = "\n\n".join(f"[صفحة {hit.page}]\n{hit.text}" for hit in hits)
    return f"المقاطع:\n\n{passages}\n\nالسؤال: {question}"
